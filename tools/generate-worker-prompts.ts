// Generated embedding lets application prompt rendering consume templates without doing I/O.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const assets = {
  qualityWorker: "quality-worker-instructions.md",
  qualityDelta: "quality-delta-instructions.md",
  skeleton: "worker-prompt.md",
  restrictions: "runtime-worker-restrictions.md",
  report: "runtime-worker-report.md",
  qualityChecks: "runtime-quality-checks.md",
  developerChecks: "runtime-developer-checks.md",
  skillInstructions: "runtime-skill-instructions.md",
};
const content = Object.fromEntries(
  Object.entries(assets).map(([key, name]) => [
    key,
    readFileSync(new URL(`../templates/prompts/${name}`, import.meta.url), "utf8").trimEnd(),
  ]),
);
const target = fileURLToPath(
  new URL("../src/application/services/worker-prompt-assets.ts", import.meta.url),
);
const source = await format(
  `// Generated by tools/generate-worker-prompts.ts. Edit templates/prompts/ instead.\nexport const workerPromptAssets = ${JSON.stringify(content)} as const;\n`,
  { parser: "typescript", printWidth: 100 },
);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source)
    throw new Error("WORKER_PROMPT_ASSETS_DRIFT: run node tools/generate-worker-prompts.ts");
} else writeFileSync(target, source);
